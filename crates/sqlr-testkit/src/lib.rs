/// Where the integration tests find their database servers.
///
/// `local` runs the servers as native processes started by `scripts/test-services.sh`
/// (`initdb`, `mysqld`, `redis-server`); `docker` starts them with
/// `docker-compose.test.yml`. The default is `local`, so a checkout without Docker still
/// runs the Postgres, MySQL and Redis suites.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Backend {
    Local,
    Docker,
}

/// The backend selected by `SQLR_TEST_BACKEND` (`local` when unset).
pub fn backend() -> Backend {
    static BACKEND: std::sync::OnceLock<Backend> = std::sync::OnceLock::new();
    *BACKEND.get_or_init(|| match std::env::var("SQLR_TEST_BACKEND").as_deref() {
        Ok("docker") => Backend::Docker,
        Ok("local") | Ok("") | Err(_) => Backend::Local,
        Ok(other) => panic!("SQLR_TEST_BACKEND must be `local` or `docker`, not `{other}`"),
    })
}

/// Whether container-backed tests should return early because the environment asks for a
/// Docker-free run (`SQLR_SKIP_CONTAINER_TESTS=1`).
pub fn skip_container_tests() -> bool {
    static SKIP: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *SKIP.get_or_init(|| std::env::var("SQLR_SKIP_CONTAINER_TESTS").is_ok_and(|value| value == "1"))
}

/// Whether the named service can run in this environment.
///
/// In the local backend only Postgres, MySQL and Redis have native services. MariaDB is
/// available when `SQLR_TEST_MARIADB` points at a server; every other service needs the
/// Docker backend. In the Docker backend every service is available (compose starts them).
pub fn service_available(name: &str) -> bool {
    if skip_container_tests() {
        return false;
    }
    match backend() {
        Backend::Docker => true,
        Backend::Local => match name {
            "POSTGRES" | "POSTGRES_GLOBAL" | "MYSQL" | "MYSQL_GLOBAL" | "MYSQL_NOTLS" | "REDIS"
            | "REDIS_TLS" => true,
            "MARIADB" | "MARIADB_GLOBAL" | "MARIADB_NOTLS" => {
                std::env::var("SQLR_TEST_MARIADB").is_ok()
            }
            _ => false,
        },
    }
}

/// The `host:port` of a fixed test service (`SQLR_TEST_POSTGRES`, `SQLR_TEST_MYSQL`, …).
///
/// The compose file publishes these ports; an environment variable overrides one when
/// the services run elsewhere.
pub fn service(name: &str) -> (String, u16) {
    if let Ok(value) = std::env::var(format!("SQLR_TEST_{name}"))
        && let Some((host, port)) = value.rsplit_once(':')
        && let Ok(port) = port.parse()
    {
        return (host.to_string(), port);
    }
    let port = match name {
        "POSTGRES" => 55432,
        "POSTGRES_GLOBAL" => 55433,
        "MYSQL" => 53306,
        "MARIADB" => 53307,
        "MYSQL_GLOBAL" => 53310,
        "MARIADB_GLOBAL" => 53311,
        "MYSQL_NOTLS" => 53312,
        "MARIADB_NOTLS" => 53313,
        "MONGO" => 57017,
        "MONGO_AUTH" => 57018,
        "REDIS" => 56379,
        "REDIS_TLS" => 56380,
        "ELASTIC" => 59200,
        "ELASTIC7" => 59201,
        "ELASTIC_AUTH" => 59202,
        "MSSQL" => 51433,
        "ORACLE" => 51521,
        other => panic!("unknown test service `{other}`"),
    };
    ("127.0.0.1".to_string(), port)
}

/// The CA certificate generated by `scripts/test-services.sh` for the TLS services.
pub fn ca_path() -> std::path::PathBuf {
    if let Ok(path) = std::env::var("SQLR_TEST_CA") {
        return path.into();
    }
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../.test-services/certs/ca.crt")
}

/// A cross-process lock for the few tests that touch server-global state.
///
/// nextest runs every test in its own process, so a `Mutex` cannot serialize them. The
/// lock is released when the guard drops (or the process exits).
pub struct TestLock {
    file: std::fs::File,
}

impl TestLock {
    pub fn acquire(name: &str) -> Self {
        let path = std::env::temp_dir().join(format!("sqlr-test-{name}.lock"));
        let file = std::fs::OpenOptions::new()
            .create(true)
            .truncate(false)
            .read(true)
            .write(true)
            .open(&path)
            .unwrap_or_else(|e| panic!("open lock {}: {e}", path.display()));
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(300);
        loop {
            match fs2::FileExt::try_lock_exclusive(&file) {
                Ok(()) => return Self { file },
                Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                    if std::time::Instant::now() >= deadline {
                        panic!("timed out waiting for the `{name}` test lock");
                    }
                    std::thread::sleep(std::time::Duration::from_millis(25));
                }
                Err(e) => panic!("lock `{name}`: {e}"),
            }
        }
    }
}

impl Drop for TestLock {
    fn drop(&mut self) {
        let _ = fs2::FileExt::unlock(&self.file);
    }
}

/// A database name unique across tests, processes and runs: for a shared server every
/// test gets its own database without colliding with a previous run.
pub fn unique_name(prefix: &str) -> String {
    use std::sync::OnceLock;
    use std::sync::atomic::{AtomicU64, Ordering};

    static RUN: OnceLock<String> = OnceLock::new();
    static NEXT: AtomicU64 = AtomicU64::new(0);

    let run = RUN.get_or_init(|| {
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos();
        format!("{nanos:x}_{}", std::process::id())
    });
    format!("{prefix}_{run}_{}", NEXT.fetch_add(1, Ordering::Relaxed))
}

/// Returns early from a container-backed test when the service cannot run.
///
/// With no argument the test needs Docker: it returns early in every non-Docker backend,
/// or when `SQLR_SKIP_CONTAINER_TESTS=1`. With a service name (`"POSTGRES"`, `"MYSQL"`,
/// `"REDIS"`, …) the test runs whenever [`service_available`] says the service can run,
/// which in the default local backend means the three native servers.
#[macro_export]
macro_rules! skip_container_tests {
    () => {
        if $crate::skip_container_tests() || $crate::backend() == $crate::Backend::Local {
            return;
        }
    };
    ($service:expr) => {
        if !$crate::service_available($service) {
            return;
        }
    };
}

