/// Backtick identifier quotes.
const BACKTICK_IDENTS: &[(u8, u8)] = &[(b'`', b'`')];

static MYSQL: LazyLock<Arc<SqlSyntax>> = LazyLock::new(|| {
    let sorted = |list: &[&'static str]| {
        let mut v = list.to_vec();
        v.sort_unstable();
        v.dedup();
        v
    };
    Arc::new(SqlSyntax {
        keywords: sorted(MYSQL_KEYWORDS),
        reserved: sorted(MYSQL_RESERVED),
        functions: sorted(MYSQL_FUNCTIONS),
        dollar_quotes: false,
        nested_comments: false,
        escape_strings: false,
        line_comment: "--",
        line_comment_needs_space: true,
        hash_comments: true,
        ident_quotes: BACKTICK_IDENTS,
        double_quote_strings: true,
        backslash_escapes: true,
        grammar: "sequel",
    })
});

/// The shared MySQL/MariaDB syntax.
pub fn mysql_syntax() -> Arc<SqlSyntax> {
    MYSQL.clone()
}

#[cfg(test)]
mod tests {
    use super::*;
    use sqlr_core::{LexState, StatementClass, TokenKind, TxVerb};

    fn kinds(text: &str) -> Vec<(TokenKind, &str)> {
        let mut tokens = Vec::new();
        mysql_syntax().lex(text, LexState::Normal, &mut tokens);
        tokens
            .iter()
            .map(|t| (t.kind, &text[t.start..t.end]))
            .collect()
    }

    #[test]
    fn keyword_lists() {
        let s = mysql_syntax();
        assert!(s.is_keyword("select"));
        assert!(s.is_reserved("ORDER"));
        assert!(!s.is_reserved("name"));
        assert!(s.is_function("group_concat"));
        assert_eq!(s.quote_if_needed("name"), "name");
        assert_eq!(s.quote_if_needed("order"), "`order`");
        assert_eq!(s.quote_if_needed("a`b"), "`a``b`");
    }

    #[test]
    fn comments_and_quotes() {
        use TokenKind::*;
        let text = "# note\nselect `a``b`, \"x\\\"y\" -- c\n--x";
        assert_eq!(
            kinds(text),
            [
                (Comment, "# note"),
                (Keyword, "select"),
                (QuotedIdent, "`a``b`"),
                (Punct, ","),
                (String, "\"x\\\"y\""),
                (Comment, "-- c"),
                (Operator, "--"),
                (Ident, "x"),
            ]
        );
        // Executable comments are highlighted as comments.
        assert_eq!(
            kinds("/*!40101 SET x = 1 */ select 1")[0],
            (Comment, "/*!40101 SET x = 1 */")
        );
        // No dollar quotes: `$$a$$` is not a string.
        assert!(kinds("select $$a$$").iter().all(|(k, _)| *k != String));
    }

    #[test]
    fn split_and_classify() {
        let s = mysql_syntax();
        let text = "select ';' # ; not a split\n; insert into t values ('a\\';b')";
        let ranges = s.split(text, LexState::Normal);
        assert_eq!(ranges.len(), 2, "{ranges:?}");
        assert_eq!(
            s.classify("start transaction"),
            StatementClass::Transaction(TxVerb::Begin)
        );
        assert_eq!(s.classify("select 1 # drop table t"), StatementClass::Read);
        assert!(matches!(
            s.classify("delete from t"),
            StatementClass::Destructive(_)
        ));
    }
}
