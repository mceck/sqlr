//! The Constraints sub-tab: primary key, unique and check constraints (foreign keys have
//! their own sub-tab).

use sqlr_core::{ConstraintDef, SqlSyntax, TableDef};

use super::{caption, expr_field, form_grid, master_detail, optional_text, sql_view};
use crate::theme::{self, Spacing, icons};

fn label(c: &ConstraintDef) -> String {
    let name = c.name().map(|n| format!("{n} ")).unwrap_or_default();
    match c {
        ConstraintDef::PrimaryKey { columns, .. } => {
            format!("{name}PRIMARY KEY ({})", columns.join(", "))
        }
        ConstraintDef::Unique { columns, .. } => format!("{name}UNIQUE ({})", columns.join(", ")),
        ConstraintDef::Check { expression, .. } => format!("{name}CHECK ({expression})"),
        ConstraintDef::Raw { definition, .. } => format!("{name}{definition}"),
        ConstraintDef::ForeignKey { .. } => format!("{name}FOREIGN KEY"),
    }
}

/// `selected` indexes `table.constraints`.
pub(super) fn constraints_tab(
    ui: &mut egui::Ui,
    table: &mut TableDef,
    selected: &mut Option<usize>,
    syntax: &SqlSyntax,
) {
    let p = theme::palette(ui.ctx());
    let shown: Vec<usize> = (0..table.constraints.len())
        .filter(|&i| !table.constraints[i].is_foreign_key())
        .collect();
    let has_pk = table.primary_key().is_some();
    let first = table.columns.first().map(|c| vec![c.name.clone()]);
    let mut added = None;
    ui.horizontal(|ui| {
        ui.spacing_mut().item_spacing.x = Spacing::S;
        if !has_pk
            && icons::short_button(
                ui,
                true,
                icons::KEY,
                Some(p.icon_key),
                "Primary key",
                "Add primary key",
            )
            .clicked()
        {
            added = Some(ConstraintDef::PrimaryKey {
                name: None,
                columns: first.clone().unwrap_or_default(),
            });
        }
        if icons::short_button(
            ui,
            true,
            icons::ADD,
            Some(p.success),
            "Unique",
            "Add unique",
        )
        .clicked()
        {
            added = Some(ConstraintDef::Unique {
                name: None,
                columns: first.clone().unwrap_or_default(),
            });
        }
        if icons::short_button(ui, true, icons::ADD, Some(p.success), "Check", "Add check")
            .clicked()
        {
            added = Some(ConstraintDef::Check {
                name: None,
                expression: String::new(),
            });
        }
        let current = selected.filter(|i| shown.contains(i));
        if icons::delete_button(ui, current.is_some(), "Delete constraint").clicked()
            && let Some(i) = current
        {
            table.constraints.remove(i);
            *selected = None;
        }
    });
    if let Some(c) = added {
        table.constraints.push(c);
        *selected = Some(table.constraints.len() - 1);
    }
    ui.add_space(Spacing::S);
    let shown: Vec<usize> = (0..table.constraints.len())
        .filter(|&i| !table.constraints[i].is_foreign_key())
        .collect();
    let names: Vec<String> = shown
        .iter()
        .map(|&i| label(&table.constraints[i]))
        .collect();
    let mut position = selected.and_then(|i| shown.iter().position(|&s| s == i));
    let columns: Vec<String> = table.columns.iter().map(|c| c.name.clone()).collect();
    master_detail(
        ui,
        "constraints",
        &names,
        &mut position,
        "No constraints",
        |ui, k| constraint_form(ui, &mut table.constraints[shown[k]], &columns, syntax),
    );
    *selected = position.map(|k| shown[k]);
}

fn constraint_form(
    ui: &mut egui::Ui,
    c: &mut ConstraintDef,
    columns: &[String],
    syntax: &SqlSyntax,
) {
    match c {
        ConstraintDef::PrimaryKey { name, columns: on }
        | ConstraintDef::Unique { name, columns: on } => {
            form_grid(ui, "constraint", |ui| {
                caption(ui, "Name");
                optional_text(ui, name, 240.0, "generated by the server");
                ui.end_row();
            });
            ui.add_space(Spacing::S);
            caption(ui, "Columns");
            column_checks(ui, on, columns);
        }
        ConstraintDef::Check { name, expression } => {
            form_grid(ui, "constraint", |ui| {
                caption(ui, "Name");
                optional_text(ui, name, 240.0, "generated by the server");
                ui.end_row();
                caption(ui, "Check");
                let mut expr = Some(expression.clone()).filter(|e| !e.is_empty());
                if expr_field(ui, &mut expr, syntax, 360.0, "condition expression").changed() {
                    *expression = expr.unwrap_or_default();
                }
                ui.end_row();
            });
        }
        ConstraintDef::Raw { name, definition } => {
            form_grid(ui, "constraint", |ui| {
                caption(ui, "Name");
                optional_text(ui, name, 240.0, "");
                ui.end_row();
            });
            caption(ui, "Written as the server prints it:");
            sql_view(ui, "raw_constraint", definition, syntax, 120.0);
        }
        ConstraintDef::ForeignKey { .. } => {}
    }
}

/// Checkboxes over the table's columns; `on` keeps the order columns were checked in.
pub(super) fn column_checks(ui: &mut egui::Ui, on: &mut Vec<String>, columns: &[String]) {
    ui.horizontal_wrapped(|ui| {
        for c in columns {
            let mut checked = on.contains(c);
            if ui.checkbox(&mut checked, c).changed() {
                if checked {
                    on.push(c.clone());
                } else {
                    on.retain(|o| o != c);
                }
            }
        }
    });
    // Columns renamed or dropped since stay listed, so the change is visible.
    let missing: Vec<&String> = on.iter().filter(|c| !columns.contains(c)).collect();
    if !missing.is_empty() {
        let names: Vec<&str> = missing.iter().map(|s| s.as_str()).collect();
        ui.colored_label(
            theme::palette(ui.ctx()).warning,
            format!("Not columns of the table: {}", names.join(", ")),
        );
    }
}
