#[tokio::test]
async fn functions_procedures_triggers_round_trip() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(OBJECTS).await;
    let trigger_ref = ObjectRef::child(ObjectKind::Trigger, &t("app", "orders"), "orders_touch");
    let trigger = match env.load(&trigger_ref).await {
        ObjectDef::Trigger(t) => t,
        other => panic!("{other:?}"),
    };
    assert_eq!(
        trigger,
        TriggerDef {
            name: "orders_touch".into(),
            table: t("app", "orders"),
            timing: "BEFORE".into(),
            events: vec!["INSERT".into(), "UPDATE OF \"note\", \"total\"".into()],
            for_each_row: true,
            condition: Some("(new.total > (0)::numeric)".into()),
            body: "app.touch()".into(),
        }
    );
    let touch = ObjectRef {
        signature: Some(String::new()),
        ..obj(ObjectKind::Function, "app", "touch")
    };
    let function = match env.load(&touch).await {
        ObjectDef::Routine(r) => r,
        other => panic!("{other:?}"),
    };
    assert_eq!(function.kind, ObjectKind::Function);
    assert_eq!(function.returns.as_deref(), Some("trigger"));
    assert_eq!(function.language.as_deref(), Some("plpgsql"));
    assert!(function.body.contains("coalesce(NEW.note, 'n/a')"));

    let add = ObjectRef {
        signature: Some("a integer, b integer".into()),
        ..obj(ObjectKind::Function, "app", "add")
    };
    let add_def = match env.load(&add).await {
        ObjectDef::Routine(r) => r,
        other => panic!("{other:?}"),
    };
    assert_eq!(
        add_def,
        RoutineDef {
            schema: Some("app".into()),
            name: "add".into(),
            kind: ObjectKind::Function,
            arguments: "a integer, b integer DEFAULT 1".into(),
            identity_arguments: Some("a integer, b integer".into()),
            returns: Some("integer".into()),
            language: Some("sql".into()),
            body: "SELECT a + b".into(),
            options: vec![
                ("volatility".into(), "IMMUTABLE".into()),
                ("strict".into(), "true".into()),
            ],
        }
    );
    // Replace the body; the function keeps its name and arguments.
    let mut replaced = add_def.clone();
    replaced.body = "SELECT a + b + 1".into();
    env.apply(&[SchemaChange::ReplaceRoutine(replaced.clone())])
        .await;
    assert_eq!(env.load(&add).await, ObjectDef::Routine(replaced));
    let row = env.raw.query_one("SELECT app.add(1)", &[]).await.unwrap();
    assert_eq!(row.get::<_, i32>(0), 3);

    let reset = ObjectRef {
        signature: Some("IN x integer".into()),
        ..obj(ObjectKind::Procedure, "app", "reset")
    };
    let procedure = env.load(&reset).await;
    match &procedure {
        ObjectDef::Routine(r) => {
            assert_eq!(r.kind, ObjectKind::Procedure);
            assert_eq!(r.returns, None);
            assert_eq!(r.options, [("security".to_string(), "DEFINER".to_string())]);
        }
        other => panic!("{other:?}"),
    }

    // Drop all three and recreate them from their DDL.
    let defs = [
        ObjectDef::Routine(function),
        procedure.clone(),
        ObjectDef::Trigger(trigger.clone()),
    ];
    env.raw
        .batch_execute("DROP FUNCTION app.touch() CASCADE; DROP PROCEDURE app.reset")
        .await
        .unwrap();
    let changes: Vec<SchemaChange> = defs.iter().cloned().map(SchemaChange::Create).collect();
    env.apply(&changes).await;
    assert_eq!(env.load(&touch).await, defs[0]);
    assert_eq!(env.load(&reset).await, defs[1]);
    assert_eq!(env.load(&trigger_ref).await, defs[2]);
    // The trigger fires.
    env.raw
        .batch_execute("INSERT INTO app.customers VALUES (1, 'a'); INSERT INTO app.orders (customer, total) VALUES (1, 5)")
        .await
        .unwrap();
    let row = env
        .raw
        .query_one("SELECT note FROM app.orders", &[])
        .await
        .unwrap();
    assert_eq!(row.get::<_, String>(0), "n/a");
}

/// Constructs the model cannot express are kept as the server prints them, never lost.
#[tokio::test]
async fn table_ddl_keeps_what_the_model_cannot_express() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(
        "CREATE TABLE p (id int PRIMARY KEY);
         CREATE TABLE t (
             id int PRIMARY KEY,
             p_id int REFERENCES p (id) DEFERRABLE INITIALLY DEFERRED,
             q_id int REFERENCES p (id) DEFERRABLE,
             name text,
             during int4range,
             EXCLUDE USING gist (during WITH &&));
         CREATE INDEX t_name ON t (name text_pattern_ops DESC NULLS LAST);
         ALTER TABLE t ADD CONSTRAINT t_id_positive CHECK (id > 0) NOT VALID;",
    )
    .await;
    let rel = env.conn.relational().unwrap();
    let node = sqlr_core::Node {
        path: sqlr_core::NodePath(vec!["public".into(), "tables".into(), "t".into()]),
        name: "t".into(),
        kind: sqlr_core::NodeKind::Table,
        has_children: true,
        detail: None,
    };
    let ddl = rel.ddl(&node).await.unwrap();
    for fragment in [
        "EXCLUDE USING gist (during WITH &&)",
        "text_pattern_ops DESC NULLS LAST",
        "DEFERRABLE INITIALLY DEFERRED",
        "CHECK ((id > 0)) NOT VALID",
    ] {
        assert!(ddl.contains(fragment), "{fragment}\n---\n{ddl}");
    }
    let before = env.table("public", "t").await;
    let deferred: Vec<(bool, bool)> = before
        .constraints
        .iter()
        .filter_map(|c| match c {
            ConstraintDef::ForeignKey {
                deferrable,
                initially_deferred,
                ..
            } => Some((*deferrable, *initially_deferred)),
            _ => None,
        })
        .collect();
    assert_eq!(deferred, [(true, true), (true, false)]);
    let statements = env
        .generator()
        .ddl(&[SchemaChange::Create(ObjectDef::Table(before.clone()))])
        .unwrap();
    env.raw.batch_execute("DROP TABLE t").await.unwrap();
    env.run(&statements).await;
    assert_eq!(env.table("public", "t").await, before);
    // Unchanged raw parts produce no changes.
    assert_eq!(diff_table(&before, &before.clone()), []);
}

/// A routine's reference names it by its identity arguments, without DEFAULT clauses, so
/// it loads, renames, takes comments and drops.
#[tokio::test]
async fn routine_with_defaults_is_named_by_identity_arguments() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(
        "CREATE FUNCTION public.f(a int, b text DEFAULT 'x') RETURNS int LANGUAGE sql
             AS 'SELECT a';",
    )
    .await;
    let loaded = env
        .load(&ObjectRef {
            signature: Some("a integer, b text".into()),
            ..obj(ObjectKind::Function, "public", "f")
        })
        .await;
    let object = loaded.object_ref();
    assert_eq!(object.signature.as_deref(), Some("a integer, b text"));
    assert_eq!(env.load(&object).await, loaded);
    env.apply(&[
        SchemaChange::SetComment {
            object: object.clone(),
            column: None,
            comment: Some("adds".into()),
        },
        SchemaChange::Rename {
            object: object.clone(),
            to: "g".into(),
        },
    ])
    .await;
    let renamed = ObjectRef {
        name: "g".into(),
        ..object
    };
    env.load(&renamed).await;
    env.apply(&[SchemaChange::Drop {
        object: renamed.clone(),
        cascade: false,
    }])
    .await;
    assert!(env.introspect().load_object(&renamed).await.is_err());
}

/// Replacing a materialized view (drop and create) creates its indexes again.
#[tokio::test]
async fn replacing_a_materialized_view_keeps_its_indexes() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(
        "CREATE TABLE t (id int PRIMARY KEY, n int);
         CREATE MATERIALIZED VIEW m AS SELECT id, n FROM t;
         CREATE UNIQUE INDEX m_id ON m (id);",
    )
    .await;
    let view = match env
        .load(&obj(ObjectKind::MaterializedView, "public", "m"))
        .await
    {
        ObjectDef::View(v) => v,
        other => panic!("{other:?}"),
    };
    let mut replaced = view.clone();
    replaced.query = "SELECT id, n + 1 AS n FROM t".into();
    env.apply(&[SchemaChange::ReplaceView(replaced)]).await;
    let row = env
        .raw
        .query_one(
            "SELECT count(*) FROM pg_indexes WHERE tablename = 'm' AND indexname = 'm_id'",
            &[],
        )
        .await
        .unwrap();
    assert_eq!(row.get::<_, i64>(0), 1);
    match env
        .load(&obj(ObjectKind::MaterializedView, "public", "m"))
        .await
    {
        ObjectDef::View(v) => assert!(v.query.contains("n + 1"), "{}", v.query),
        other => panic!("{other:?}"),
    }
}

/// Explorer nodes of functions and procedures map to the right references, whatever
/// parentheses their names and argument types hold.
#[tokio::test]
async fn function_and_procedure_nodes_map_to_their_objects() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(
        r#"CREATE FUNCTION public."we(ird" (a numeric(10,2)) RETURNS int LANGUAGE sql AS 'SELECT 1';
           CREATE PROCEDURE public.p (x int) LANGUAGE sql AS 'SELECT 1';"#,
    )
    .await;
    let nodes = env
        .conn
        .browse(&sqlr_core::NodePath(vec![
            "public".into(),
            "functions".into(),
        ]))
        .await
        .unwrap();
    let rel = env.conn.relational().unwrap();
    let kinds: Vec<(String, sqlr_core::NodeKind, ObjectKind)> = nodes
        .iter()
        .map(|n| {
            let object = rel
                .object_ref(n)
                .unwrap_or_else(|| panic!("no object for {n:?}"));
            (n.name.clone(), n.kind, object.kind)
        })
        .collect();
    assert_eq!(
        kinds,
        [
            (
                "p(IN x integer)".to_string(),
                sqlr_core::NodeKind::Procedure,
                ObjectKind::Procedure
            ),
            (
                "we(ird(a numeric)".to_string(),
                sqlr_core::NodeKind::Function,
                ObjectKind::Function
            ),
        ]
    );
    for n in &nodes {
        let object = rel.object_ref(n).unwrap();
        env.load(&object).await;
        assert!(rel.ddl(n).await.is_ok(), "{n:?}");
    }
}

