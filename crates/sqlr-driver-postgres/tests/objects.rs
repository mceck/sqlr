/// The Round-trip rule: load → create DDL → drop → run the DDL → load yields the same
/// definition, for every kind the manifest says it can create.
#[tokio::test]
async fn round_trip_every_creatable_kind() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(OBJECTS).await;
    let shop = unique_name("shop");
    env.raw
        .batch_execute(&format!(r#"CREATE DATABASE "{shop}""#))
        .await
        .unwrap();
    let editing = PostgresDriver::new().manifest().editing.clone().unwrap();
    let orders = t("app", "orders");
    let routine = |kind, name: &str, signature: &str| ObjectRef {
        signature: Some(signature.into()),
        ..obj(kind, "app", name)
    };
    // Dependents first: dropping a table drops its views, indexes and triggers.
    let cases: Vec<(ObjectRef, String)> = vec![
        (
            ObjectRef::child(ObjectKind::Trigger, &orders, "orders_touch"),
            "DROP TRIGGER orders_touch ON app.orders".into(),
        ),
        (
            ObjectRef::child(ObjectKind::Index, &orders, "orders_note"),
            "DROP INDEX app.orders_note".into(),
        ),
        (
            obj(ObjectKind::View, "app", "big_orders"),
            "DROP VIEW app.big_orders".into(),
        ),
        (
            obj(ObjectKind::MaterializedView, "app", "totals"),
            "DROP MATERIALIZED VIEW app.totals".into(),
        ),
        (
            obj(ObjectKind::Sequence, "app", "seq"),
            "DROP SEQUENCE app.seq".into(),
        ),
        (
            routine(ObjectKind::Function, "add", "a integer, b integer"),
            "DROP FUNCTION app.add".into(),
        ),
        (
            routine(ObjectKind::Procedure, "reset", "IN x integer"),
            "DROP PROCEDURE app.reset".into(),
        ),
        (
            obj(ObjectKind::Table, "app", "orders"),
            "DROP TABLE app.orders CASCADE".into(),
        ),
        (
            ObjectRef {
                kind: ObjectKind::Schema,
                database: None,
                schema: None,
                name: "empty_one".into(),
                parent: None,
                signature: None,
            },
            "DROP SCHEMA empty_one".into(),
        ),
        (
            ObjectRef {
                kind: ObjectKind::Database,
                database: None,
                schema: None,
                name: shop.clone(),
                parent: None,
                signature: None,
            },
            format!(r#"DROP DATABASE "{shop}""#),
        ),
    ];
    let mut covered = Vec::new();
    for (object, drop) in &cases {
        let before = env.load(object).await;
        let statements = env
            .generator()
            .ddl(&[SchemaChange::Create(before.clone())])
            .unwrap();
        env.raw.batch_execute(drop).await.unwrap();
        env.run(&statements).await;
        let after = env.load(object).await;
        assert_eq!(after, before, "{object:?}\n{statements:#?}");
        covered.push(object.kind);
    }
    for kind in &editing.create {
        assert!(covered.contains(kind), "{kind:?} has no round trip");
    }

    // The table brought back its index and trigger.
    let orders_def = env.table("app", "orders").await;
    assert_eq!(orders_def.indexes.len(), 1);
    assert_eq!(orders_def.triggers.len(), 1);
    assert_eq!(orders_def.comment.as_deref(), Some("All orders"));
}

#[tokio::test]
async fn ddl_awkward_names_per_dialect() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(r#"CREATE SCHEMA "Sch ""q"" ü""#).await;
    let schema = "Sch \"q\" ü";
    let parent_ref = t(schema, "Párent 'p'");
    let mut parent = TableDef::new(parent_ref.clone());
    parent.columns = vec![col("ID", "integer", false)];
    parent.constraints.push(ConstraintDef::PrimaryKey {
        name: Some("pk \"p\"".into()),
        columns: vec!["ID".into()],
    });
    let table = t(schema, "Wé \"ird\" 'name'");
    let mut def = TableDef::new(table.clone());
    def.columns = vec![
        col("select", "integer", false),
        ColumnDef {
            comment: Some("it's\nmulti-line \"quoted\"".into()),
            default: Some("'it''s'::text".into()),
            ..col("MixedCase", "text", true)
        },
        col("ünï code", "integer", true),
        col("a\"b", "integer", true),
    ];
    def.constraints = vec![
        ConstraintDef::PrimaryKey {
            name: Some("pk \"x\"".into()),
            columns: vec!["select".into()],
        },
        ConstraintDef::Unique {
            name: Some("uq 'u'".into()),
            columns: vec!["ünï code".into(), "a\"b".into()],
        },
        ConstraintDef::ForeignKey {
            name: Some("fk;drop".into()),
            columns: vec!["a\"b".into()],
            target: parent_ref.clone(),
            target_columns: vec!["ID".into()],
            on_update: FkAction::NoAction,
            on_delete: FkAction::SetNull,
            deferrable: false,
            initially_deferred: false,
        },
        ConstraintDef::Check {
            name: Some("chk 'c'".into()),
            expression: "(\"select\" > 0)".into(),
        },
    ];
    def.indexes = vec![IndexDef {
        name: "idx \"x\"".into(),
        columns: vec![IndexColumn {
            desc: true,
            ..IndexColumn::column("MixedCase")
        }],
        method: Some("btree".into()),
        ..Default::default()
    }];
    def.comment = Some("O'Reilly;\n-- not a comment".into());
    env.apply(&[
        SchemaChange::Create(ObjectDef::Table(parent)),
        SchemaChange::Create(ObjectDef::Table(def.clone())),
    ])
    .await;
    assert_eq!(env.table(schema, &table.name).await, def);

    // Rename, comment and drop with the same names.
    let mut renamed = def.clone();
    renamed.columns[1].name = "Other \"one\"".into();
    renamed.indexes[0].columns[0].expr = "Other \"one\"".into();
    renamed.columns[1].comment = None;
    env.apply(&diff_table(&def, &renamed)).await;
    assert_eq!(env.table(schema, &table.name).await, renamed);
    env.apply(&[SchemaChange::Drop {
        object: ObjectRef::relation(ObjectKind::Table, &table),
        cascade: false,
    }])
    .await;
    assert!(
        env.introspect()
            .load_object(&ObjectRef::relation(ObjectKind::Table, &table))
            .await
            .is_err()
    );
}

#[tokio::test]
async fn alter_column_type_nullability_default() {
    sqlr_testkit::skip_container_tests!();
    let env =
        Env::new("CREATE TABLE t (id int PRIMARY KEY, a text, b int NOT NULL, c int DEFAULT 7)")
            .await;
    let before = env.table("public", "t").await;
    let mut after = before.clone();
    after.columns[1].type_name = "character varying(20)".into();
    after.columns[1].nullable = false;
    after.columns[2].nullable = true;
    after.columns[2].default = Some("42".into());
    after.columns[3].default = None;
    after.columns[3].type_name = "bigint".into();
    env.raw
        .batch_execute("INSERT INTO t VALUES (1, 'x', 2, 3)")
        .await
        .unwrap();
    let statements = env.apply(&diff_table(&before, &after)).await;
    assert!(
        statements
            .iter()
            .any(|s| s.contains("TYPE character varying(20) USING \"a\"::character varying(20)")),
        "{statements:#?}"
    );
    assert_eq!(env.table("public", "t").await, after);
    // Back again.
    env.apply(&diff_table(&after, &before)).await;
    assert_eq!(env.table("public", "t").await, before);
}

#[tokio::test]
async fn add_drop_fk_check_unique_index() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(
        "CREATE TABLE p (id int PRIMARY KEY);
         CREATE TABLE c (id int PRIMARY KEY, p_id int, qty int, code text)",
    )
    .await;
    let before = env.table("public", "c").await;
    let mut after = before.clone();
    after.constraints.push(ConstraintDef::Unique {
        name: Some("c_code_key".into()),
        columns: vec!["code".into()],
    });
    after.constraints.push(ConstraintDef::ForeignKey {
        name: Some("c_p_fk".into()),
        columns: vec!["p_id".into()],
        target: t("public", "p"),
        target_columns: vec!["id".into()],
        on_update: FkAction::Cascade,
        on_delete: FkAction::Restrict,
        deferrable: true,
        initially_deferred: false,
    });
    after.constraints.push(ConstraintDef::Check {
        name: Some("c_qty_check".into()),
        expression: "(qty > 0)".into(),
    });
    after.indexes.push(IndexDef {
        name: "c_qty".into(),
        columns: vec![IndexColumn::column("qty")],
        unique: false,
        method: Some("hash".into()),
        ..Default::default()
    });
    let changes = diff_table(&before, &after);
    assert_eq!(changes.len(), 4, "{changes:#?}");
    env.apply(&changes).await;
    let loaded = env.table("public", "c").await;
    // Constraints load in a fixed order: primary key, unique, foreign keys, checks.
    let mut expected = after.clone();
    expected.constraints = vec![
        after.constraints[0].clone(),
        after.constraints[1].clone(),
        after.constraints[2].clone(),
        after.constraints[3].clone(),
    ];
    assert_eq!(loaded, expected);
    env.apply(&diff_table(&loaded, &before)).await;
    assert_eq!(env.table("public", "c").await, before);
}

