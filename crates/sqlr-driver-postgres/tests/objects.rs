//! Object introspection and DDL generation against PostgreSQL 17.

mod support;

use std::sync::Arc;

use sqlr_core::{
    ColumnDef, Connection, ConnectionConfig, ConstraintDef, DdlGen, Driver, FkAction, Identity,
    IndexColumn, IndexDef, Introspect, ObjectDef, ObjectKind, ObjectRef, PartitionDef, Placement,
    RoutineDef, SchemaChange, Secrets, TableDef, TableRef, TriggerDef, diff_table,
};
use sqlr_driver_postgres::PostgresDriver;
use sqlr_testkit::unique_name;
use support::{PgServer, pg};

struct Env {
    _c: PgServer,
    cfg: ConnectionConfig,
    sec: Secrets,
    raw: tokio_postgres::Client,
    conn: Arc<dyn Connection>,
}

async fn raw(cfg: &ConnectionConfig, sec: &Secrets, database: &str) -> tokio_postgres::Client {
    let (client, conn) = tokio_postgres::Config::new()
        .host(cfg.values["host"].as_str())
        .port(cfg.values["port"].parse().unwrap())
        .user("postgres")
        .password(&sec.0["password"])
        .dbname(database)
        .connect(tokio_postgres::NoTls)
        .await
        .unwrap();
    tokio::spawn(conn);
    client
}

impl Env {
    async fn new(setup: &str) -> Self {
        let (c, cfg, sec) = pg().await;
        let raw = raw(&cfg, &sec, &cfg.values["database"]).await;
        raw.batch_execute(setup).await.unwrap();
        let conn = PostgresDriver::new().connect(&cfg, &sec).await.unwrap();
        Self {
            _c: c,
            cfg,
            sec,
            raw,
            conn,
        }
    }

    fn introspect(&self) -> &dyn Introspect {
        self.conn.relational().unwrap().introspect().unwrap()
    }

    fn generator(&self) -> &dyn DdlGen {
        self.conn.relational().unwrap().dialect().ddl_gen().unwrap()
    }

    async fn load(&self, object: &ObjectRef) -> ObjectDef {
        self.introspect()
            .load_object(object)
            .await
            .unwrap_or_else(|e| panic!("{object:?}: {e:?}"))
    }

    async fn table(&self, schema: &str, name: &str) -> TableDef {
        match self.load(&obj(ObjectKind::Table, schema, name)).await {
            ObjectDef::Table(t) => t,
            other => panic!("{other:?}"),
        }
    }

    /// Generates the statements for `changes` and runs them one by one.
    async fn apply(&self, changes: &[SchemaChange]) -> Vec<String> {
        let statements = self.generator().ddl(changes).unwrap();
        self.run(&statements).await;
        statements
    }

    /// Runs generated statements as the engine applies them (the rule on `DdlGen`): runs
    /// of `Placement::Transaction` statements inside `BEGIN` … `COMMIT`, others alone.
    async fn run(&self, statements: &[String]) {
        let exec = |s: String| async move {
            self.raw
                .batch_execute(&s)
                .await
                .unwrap_or_else(|e| panic!("{s}\n{e:?}"));
        };
        let mut open = false;
        for s in statements {
            let in_transaction = self.generator().placement(s) == Placement::Transaction;
            if in_transaction != open {
                exec(if open { "COMMIT" } else { "BEGIN" }.to_string()).await;
                open = in_transaction;
            }
            exec(s.clone()).await;
        }
        if open {
            exec("COMMIT".to_string()).await;
        }
    }
}

fn t(schema: &str, name: &str) -> TableRef {
    TableRef {
        database: None,
        schema: Some(schema.into()),
        name: name.into(),
    }
}

fn obj(kind: ObjectKind, schema: &str, name: &str) -> ObjectRef {
    ObjectRef::relation(kind, &t(schema, name))
}

fn col(name: &str, ty: &str, nullable: bool) -> ColumnDef {
    ColumnDef {
        name: name.into(),
        type_name: ty.into(),
        nullable,
        ..Default::default()
    }
}

