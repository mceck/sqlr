#[tokio::test]
async fn truncate_cascade_empties_referencing_tables() {
    sqlr_testkit::skip_container_tests!();
    let env = Env::new(
        "CREATE TABLE parent (id int PRIMARY KEY);
         CREATE TABLE child (id int PRIMARY KEY, parent int REFERENCES parent (id));
         INSERT INTO parent VALUES (1);
         INSERT INTO child VALUES (1, 1);",
    )
    .await;
    let table = TableRef {
        database: None,
        schema: Some("public".into()),
        name: "parent".into(),
    };
    let truncate = |cascade| SchemaChange::Truncate {
        table: table.clone(),
        cascade,
    };
    // Without CASCADE the referenced table cannot be truncated.
    let plain = env.generator().ddl(&[truncate(false)]).unwrap();
    assert!(env.raw.batch_execute(&plain[0]).await.is_err());
    env.apply(&[truncate(true)]).await;
    for t in ["parent", "child"] {
        let n: i64 = env
            .raw
            .query_one(&format!("SELECT count(*) FROM {t}"), &[])
            .await
            .unwrap()
            .get(0);
        assert_eq!(n, 0, "{t}");
    }
}
