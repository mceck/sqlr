static PG: LazyLock<Arc<SqlSyntax>> = LazyLock::new(|| {
    let sorted = |list: &[&'static str]| {
        let mut v = list.to_vec();
        v.sort_unstable();
        v.dedup();
        v
    };
    Arc::new(SqlSyntax {
        keywords: sorted(PG_KEYWORDS),
        reserved: sorted(PG_RESERVED),
        functions: sorted(PG_FUNCTIONS),
        dollar_quotes: true,
        nested_comments: true,
        escape_strings: true,
        line_comment: "--",
        line_comment_needs_space: false,
        hash_comments: false,
        ident_quotes: DOUBLE_QUOTE_IDENTS,
        double_quote_strings: false,
        backslash_escapes: false,
        grammar: "sequel",
    })
});

/// The shared PostgreSQL syntax.
pub fn pg_syntax() -> Arc<SqlSyntax> {
    PG.clone()
}

#[cfg(test)]
mod tests {
    use super::*;
    use sqlr_core::LexState;

    #[test]
    fn pg_keyword_lists() {
        let s = pg_syntax();
        assert!(s.is_keyword("select"));
        assert!(s.is_reserved("TABLE"));
        assert!(!s.is_reserved("name"));
        assert_eq!(s.quote_if_needed("name"), "name");
        assert_eq!(s.quote_if_needed("user"), "\"user\"");
    }

    #[test]
    fn pg_split_create_function() {
        let text = "create function f() returns int as $$ begin; return 1; end $$ language plpgsql; select 1; select 2";
        let r = pg_syntax().split(text, LexState::Normal);
        assert_eq!(r.len(), 3);
        assert_eq!(&text[r[1].clone()], "select 1");
        assert_eq!(&text[r[2].clone()], "select 2");
    }
}
