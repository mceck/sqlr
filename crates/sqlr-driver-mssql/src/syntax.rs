static TSQL: LazyLock<Arc<SqlSyntax>> = LazyLock::new(|| {
    let sorted = |list: &[&'static str]| {
        let mut v = list.to_vec();
        v.sort_unstable();
        v.dedup();
        v
    };
    let mut functions = sorted(TSQL_FUNCTIONS);
    functions.sort_unstable();
    functions.dedup();
    Arc::new(SqlSyntax {
        keywords: sorted(TSQL_KEYWORDS),
        reserved: sorted(TSQL_RESERVED),
        functions,
        dollar_quotes: false,
        nested_comments: true,
        escape_strings: false,
        line_comment: "--",
        line_comment_needs_space: false,
        hash_comments: false,
        ident_quotes: BRACKET_QUOTES,
        double_quote_strings: false,
        backslash_escapes: false,
        grammar: "sequel",
    })
});

pub fn tsql_syntax() -> Arc<SqlSyntax> {
    TSQL.clone()
}
