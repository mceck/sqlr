//! DDL generation for Oracle. Identifiers go through [`Dialect::quote_ident`]; expression
//! fields (defaults, checks, view queries) are written as is. Tables, views and indexes are
//! covered; comments, sequences, routines and triggers are not. Oracle commits before and
//! after every DDL statement, so a list of them is not atomic.

use sqlr_core::{
    ColumnDef, ConstraintDef, DdlGen, Dialect, DriverError, ErrorKind, FkAction, Identity,
    IndexDef, ObjectDef, ObjectKind, ObjectRef, SchemaChange, TableDef, TableRef, ViewDef, script,
};

use crate::dialect::OracleDialect;

fn unsupported(message: impl Into<String>) -> DriverError {
    DriverError::new(ErrorKind::Unsupported, message)
}

impl OracleDialect {
    fn q(&self, ident: &str) -> String {
        self.quote_ident(ident)
    }

    fn quoted_list(&self, names: &[String]) -> String {
        names
            .iter()
            .map(|n| self.q(n))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn column_definition(&self, c: &ColumnDef) -> String {
        let mut out = format!("{} {}", self.q(&c.name), c.type_name);
        if let Some(expr) = &c.generated {
            out.push_str(&format!(" GENERATED ALWAYS AS ({expr}) VIRTUAL"));
            return out;
        }
        match c.identity {
            Some(Identity::Always) => out.push_str(" GENERATED ALWAYS AS IDENTITY"),
            Some(_) => out.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
            None => {
                if let Some(default) = &c.default {
                    out.push_str(&format!(" DEFAULT {default}"));
                }
            }
        }
        if !c.nullable {
            out.push_str(" NOT NULL");
        }
        out
    }

    fn constraint(&self, c: &ConstraintDef) -> Result<String, DriverError> {
        let named = match c.name() {
            Some(n) => format!("CONSTRAINT {} ", self.q(n)),
            None => String::new(),
        };
        let body = match c {
            ConstraintDef::PrimaryKey { columns, .. } => {
                format!("PRIMARY KEY ({})", self.quoted_list(columns))
            }
            ConstraintDef::Unique { columns, .. } => {
                format!("UNIQUE ({})", self.quoted_list(columns))
            }
            ConstraintDef::Check { expression, .. } => format!("CHECK ({expression})"),
            ConstraintDef::ForeignKey {
                columns,
                target,
                target_columns,
                on_update,
                on_delete,
                ..
            } => {
                if !matches!(on_update, FkAction::NoAction | FkAction::Restrict) {
                    return Err(unsupported("Oracle foreign keys have no ON UPDATE action"));
                }
                let mut fk = format!(
                    "FOREIGN KEY ({}) REFERENCES {} ({})",
                    self.quoted_list(columns),
                    self.qualified(target),
                    self.quoted_list(target_columns)
                );
                match on_delete {
                    FkAction::NoAction | FkAction::Restrict => {}
                    FkAction::Cascade | FkAction::SetNull => {
                        fk.push_str(&format!(" ON DELETE {}", on_delete.sql()));
                    }
                    FkAction::SetDefault => {
                        return Err(unsupported("Oracle has no ON DELETE SET DEFAULT"));
                    }
                }
                fk
            }
            ConstraintDef::Raw { definition, .. } => definition.clone(),
        };
        Ok(format!("{named}{body}"))
    }

    fn create_index(&self, table: &TableRef, i: &IndexDef) -> Result<String, DriverError> {
        if let Some(definition) = &i.definition {
            return Ok(definition.clone());
        }
        if i.predicate.is_some() || !i.include.is_empty() {
            return Err(unsupported(
                "Oracle indexes have no WHERE or INCLUDE clause",
            ));
        }
        let kind = match i.method.as_deref().map(str::to_ascii_uppercase).as_deref() {
            None | Some("" | "NORMAL") => "",
            Some("BITMAP") => "BITMAP ",
            Some(other) => return Err(unsupported(format!("unknown index type `{other}`"))),
        };
        if i.unique && !kind.is_empty() {
            return Err(unsupported("a bitmap index cannot be unique"));
        }
        let parts: Vec<String> = i
            .columns
            .iter()
            .map(|c| {
                let mut part = if c.is_expression() {
                    c.expr.clone()
                } else {
                    self.q(&c.expr)
                };
                if c.desc {
                    part.push_str(" DESC");
                }
                part
            })
            .collect();
        let name = self.qualified(&TableRef {
            name: i.name.clone(),
            ..table.clone()
        });
        Ok(format!(
            "CREATE {}{kind}INDEX {name} ON {} ({})",
            if i.unique { "UNIQUE " } else { "" },
            self.qualified(table),
            parts.join(", ")
        ))
    }

    fn create_table(&self, t: &TableDef) -> Result<Vec<String>, DriverError> {
        let mut lines: Vec<String> = t
            .columns
            .iter()
            .map(|c| format!("    {}", self.column_definition(c)))
            .collect();
        let (fks, others): (Vec<&ConstraintDef>, Vec<&ConstraintDef>) =
            t.constraints.iter().partition(|c| c.is_foreign_key());
        for c in others.into_iter().chain(fks) {
            lines.push(format!("    {}", self.constraint(c)?));
        }
        if !t.partitions.is_empty() {
            return Err(unsupported("Oracle partitions are not supported"));
        }
        let mut out = vec![format!(
            "CREATE TABLE {} (\n{}\n)",
            self.qualified(&t.table),
            lines.join(",\n")
        )];
        for i in &t.indexes {
            out.push(self.create_index(&t.table, i)?);
        }
        Ok(out)
    }

    fn create_view(&self, v: &ViewDef, replace: bool) -> Result<String, DriverError> {
        if v.materialized {
            return Err(unsupported(
                "Oracle materialized views are not supported here",
            ));
        }
        if v.query.trim().is_empty() {
            return Err(unsupported("a view needs a query"));
        }
        Ok(format!(
            "CREATE {}VIEW {} AS {}",
            if replace { "OR REPLACE " } else { "" },
            self.qualified(&v.view),
            v.query
        ))
    }

    fn create(&self, def: &ObjectDef) -> Result<Vec<String>, DriverError> {
        Ok(match def {
            ObjectDef::Table(t) => self.create_table(t)?,
            ObjectDef::View(v) => vec![self.create_view(v, false)?],
            ObjectDef::Index { table, index } => vec![self.create_index(table, index)?],
            other => {
                return Err(unsupported(format!(
                    "cannot create a {} here",
                    other.kind().keyword().to_lowercase()
                )));
            }
        })
    }

    fn index_name(&self, o: &ObjectRef) -> String {
        self.qualified(&o.table_ref())
    }

    fn alter_column(
        &self,
        table: &TableRef,
        before: &ColumnDef,
        after: &ColumnDef,
    ) -> Result<Vec<String>, DriverError> {
        let t = self.qualified(table);
        let mut out = Vec::new();
        if before.name != after.name {
            out.push(format!(
                "ALTER TABLE {t} RENAME COLUMN {} TO {}",
                self.q(&before.name),
                self.q(&after.name)
            ));
        }
        if before.identity != after.identity {
            return Err(unsupported(
                "Oracle cannot add or remove an identity on an existing column",
            ));
        }
        if before.generated != after.generated {
            return Err(unsupported(
                "Oracle cannot change a virtual column: drop and add it",
            ));
        }
        let mut clauses = Vec::new();
        if before.type_name != after.type_name {
            clauses.push(after.type_name.clone());
        }
        if before.default != after.default && after.identity.is_none() {
            clauses.push(format!(
                "DEFAULT {}",
                after.default.as_deref().unwrap_or("NULL")
            ));
        }
        // Oracle refuses `NULL` or `NOT NULL` on a column that already is so.
        if before.nullable != after.nullable {
            clauses.push(if after.nullable { "NULL" } else { "NOT NULL" }.into());
        }
        if !clauses.is_empty() {
            out.push(format!(
                "ALTER TABLE {t} MODIFY ({} {})",
                self.q(&after.name),
                clauses.join(" ")
            ));
        }
        Ok(out)
    }

    fn change(&self, change: &SchemaChange) -> Result<Vec<String>, DriverError> {
        Ok(match change {
            SchemaChange::Create(def) => self.create(def)?,
            SchemaChange::Drop { object, cascade } => vec![match object.kind {
                ObjectKind::Index => format!("DROP INDEX {}", self.index_name(object)),
                ObjectKind::Table => format!(
                    "DROP TABLE {}{}",
                    self.qualified(&object.table_ref()),
                    if *cascade { " CASCADE CONSTRAINTS" } else { "" }
                ),
                ObjectKind::View => {
                    format!("DROP VIEW {}", self.qualified(&object.table_ref()))
                }
                other => {
                    return Err(unsupported(format!(
                        "cannot drop a {}",
                        other.keyword().to_lowercase()
                    )));
                }
            }],
            SchemaChange::Rename { object, to } => vec![match object.kind {
                ObjectKind::Table => format!(
                    "ALTER TABLE {} RENAME TO {}",
                    self.qualified(&object.table_ref()),
                    self.q(to)
                ),
                // `RENAME` works on the connected user's own objects, unqualified.
                ObjectKind::View => {
                    format!("RENAME {} TO {}", self.q(&object.name), self.q(to))
                }
                ObjectKind::Index => format!(
                    "ALTER INDEX {} RENAME TO {}",
                    self.index_name(object),
                    self.q(to)
                ),
                other => {
                    return Err(unsupported(format!(
                        "Oracle cannot rename a {}",
                        other.keyword().to_lowercase()
                    )));
                }
            }],
            SchemaChange::AddColumn { table, column } => vec![format!(
                "ALTER TABLE {} ADD {}",
                self.qualified(table),
                self.column_definition(column)
            )],
            SchemaChange::DropColumn { table, name } => vec![format!(
                "ALTER TABLE {} DROP COLUMN {}",
                self.qualified(table),
                self.q(name)
            )],
            SchemaChange::AlterColumn {
                table,
                before,
                after,
            } => self.alter_column(table, before, after)?,
            SchemaChange::AddConstraint { table, constraint } => vec![format!(
                "ALTER TABLE {} ADD {}",
                self.qualified(table),
                self.constraint(constraint)?
            )],
            SchemaChange::DropConstraint { table, name } => vec![format!(
                "ALTER TABLE {} DROP CONSTRAINT {}",
                self.qualified(table),
                self.q(name)
            )],
            SchemaChange::AddIndex { table, index, .. } => vec![self.create_index(table, index)?],
            SchemaChange::DropIndex { table, name } => vec![format!(
                "DROP INDEX {}",
                self.qualified(&TableRef {
                    name: name.clone(),
                    ..table.clone()
                })
            )],
            SchemaChange::SetComment { .. } => {
                return Err(unsupported("Oracle comments are not supported here"));
            }
            SchemaChange::ReplaceView(v) => vec![self.create_view(v, true)?],
            SchemaChange::ReplaceRoutine(_) => {
                return Err(unsupported("Oracle routines are not supported here"));
            }
            SchemaChange::SetOptions { object, .. } => {
                return Err(unsupported(format!(
                    "a {} has no options here",
                    object.kind.keyword().to_lowercase()
                )));
            }
            SchemaChange::AttachPartition { .. } | SchemaChange::DetachPartition { .. } => {
                return Err(unsupported("Oracle partitions are not supported"));
            }
            SchemaChange::Truncate { table, cascade } => vec![format!(
                "TRUNCATE TABLE {}{}",
                self.qualified(table),
                if *cascade { " CASCADE" } else { "" }
            )],
        })
    }
}

impl DdlGen for OracleDialect {
    fn ddl(&self, changes: &[SchemaChange]) -> Result<Vec<String>, DriverError> {
        let mut out = Vec::new();
        for change in changes {
            out.extend(self.change(change)?);
        }
        Ok(out)
    }

    fn create_ddl(&self, def: &ObjectDef) -> Result<String, DriverError> {
        Ok(script(&self.create(def)?))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn table(name: &str) -> TableRef {
        TableRef {
            database: None,
            schema: Some("S\"x".into()),
            name: name.into(),
        }
    }

    #[test]
    fn create_table_quotes_and_orders_clauses() {
        let mut def = TableDef::new(table("a"));
        def.columns = vec![
            ColumnDef {
                name: "id".into(),
                type_name: "NUMBER".into(),
                identity: Some(Identity::Always),
                ..Default::default()
            },
            ColumnDef {
                name: "n".into(),
                type_name: "NUMBER(3)".into(),
                default: Some("18".into()),
                ..Default::default()
            },
        ];
        def.constraints = vec![ConstraintDef::ForeignKey {
            name: Some("fk".into()),
            columns: vec!["n".into()],
            target: table("t"),
            target_columns: vec!["id".into()],
            on_update: FkAction::NoAction,
            on_delete: FkAction::SetNull,
            deferrable: false,
            initially_deferred: false,
        }];
        assert_eq!(
            OracleDialect.create_ddl(&ObjectDef::Table(def)).unwrap(),
            "CREATE TABLE \"S\"\"x\".\"a\" (\n    \"id\" NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,\n    \
             \"n\" NUMBER(3) DEFAULT 18 NOT NULL,\n    CONSTRAINT \"fk\" FOREIGN KEY (\"n\") \
             REFERENCES \"S\"\"x\".\"t\" (\"id\") ON DELETE SET NULL\n);"
        );
    }

    #[test]
    fn a_modify_only_names_what_changes() {
        let before = ColumnDef {
            name: "a".into(),
            type_name: "NUMBER(3)".into(),
            nullable: true,
            ..Default::default()
        };
        let after = ColumnDef {
            nullable: false,
            ..before.clone()
        };
        let ddl = OracleDialect
            .ddl(&[SchemaChange::AlterColumn {
                table: table("t"),
                before,
                after,
            }])
            .unwrap();
        assert_eq!(
            ddl,
            ["ALTER TABLE \"S\"\"x\".\"t\" MODIFY (\"a\" NOT NULL)"]
        );
    }

    #[test]
    fn what_oracle_cannot_do_is_unsupported() {
        let fk = ConstraintDef::ForeignKey {
            name: None,
            columns: vec!["a".into()],
            target: table("t"),
            target_columns: vec!["b".into()],
            on_update: FkAction::Cascade,
            on_delete: FkAction::NoAction,
            deferrable: false,
            initially_deferred: false,
        };
        let err = OracleDialect
            .ddl(&[SchemaChange::AddConstraint {
                table: table("t"),
                constraint: fk,
            }])
            .unwrap_err();
        assert_eq!(err.kind, ErrorKind::Unsupported);
    }
}
