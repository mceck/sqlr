static ORACLE: LazyLock<Arc<SqlSyntax>> = LazyLock::new(|| {
    let sorted = |list: &[&'static str]| {
        let mut v = list.to_vec();
        v.sort_unstable();
        v.dedup();
        v
    };
    Arc::new(SqlSyntax {
        keywords: sorted(ORACLE_KEYWORDS),
        reserved: sorted(ORACLE_RESERVED),
        functions: sorted(ORACLE_FUNCTIONS),
        dollar_quotes: false,
        nested_comments: false,
        escape_strings: false,
        line_comment: "--",
        line_comment_needs_space: false,
        hash_comments: false,
        ident_quotes: DOUBLE_QUOTE_IDENTS,
        double_quote_strings: false,
        backslash_escapes: false,
        grammar: "sequel",
    })
});

pub fn oracle_syntax() -> Arc<SqlSyntax> {
    ORACLE.clone()
}
