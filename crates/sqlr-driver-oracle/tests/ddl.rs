//! DDL written by the Oracle generator, applied to Oracle Free. An Oracle error closes the
//! connection (oracle-rs on Free), so every statement here is one that must succeed.

mod support;

use std::sync::Arc;

use sqlr_core::{
    ColumnDef, Connection, ConstraintDef, DdlGen, IndexColumn, IndexDef, ObjectDef, ObjectKind,
    ObjectRef, SchemaChange, TableDef, TableRef, ViewDef,
};
use sqlr_driver_oracle::OracleDialect;
use sqlr_testkit::unique_name;

fn table(name: &str) -> TableRef {
    TableRef {
        database: None,
        schema: Some("SQLR_TEST".into()),
        name: name.into(),
    }
}

async fn run(conn: &Arc<dyn Connection>, statements: &[String]) {
    for sql in statements {
        conn.relational()
            .unwrap()
            .execute(sql)
            .await
            .unwrap_or_else(|e| panic!("{sql}\n{e:?}"));
    }
}

async fn load(conn: &Arc<dyn Connection>, name: &str) -> TableDef {
    let snapshot = conn
        .relational()
        .unwrap()
        .introspect()
        .unwrap()
        .load_schema(None, "SQLR_TEST")
        .await
        .unwrap();
    snapshot
        .objects
        .into_iter()
        .find_map(|o| match o {
            ObjectDef::Table(t) if t.table.name == name => Some(t),
            _ => None,
        })
        .unwrap_or_else(|| panic!("table {name}"))
}

/// Drops what a test made, on a connection of its own.
async fn clean(statements: &[String]) {
    let conn = support::connect().await;
    for sql in statements {
        let _ = conn.relational().unwrap().execute(sql).await;
    }
}

fn column(name: &str, type_name: &str, nullable: bool) -> ColumnDef {
    ColumnDef {
        name: name.into(),
        type_name: type_name.into(),
        nullable,
        ..Default::default()
    }
}

#[tokio::test]
async fn created_tables_read_back_as_they_were() {
    sqlr_testkit::skip_container_tests!();
    let conn = support::connect().await;
    let g = OracleDialect;
    let base = unique_name("SQLR_DDL").to_uppercase();
    let (customers, orders) = (format!("{base}_C"), format!("{base}_O"));
    let (c2, o2) = (format!("{customers}2"), format!("{orders}2"));
    run(
        &conn,
        &[
            format!(
                "CREATE TABLE {customers} (id NUMBER(10) NOT NULL, email VARCHAR2(120) NOT NULL, \
                 age NUMBER(3) DEFAULT 18, CONSTRAINT {base}_PK PRIMARY KEY (id), \
                 CONSTRAINT {base}_UQ UNIQUE (email), CONSTRAINT {base}_CK CHECK (age >= 0))"
            ),
            format!(
                "CREATE TABLE {orders} (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
                 customer_id NUMBER(10) NOT NULL, total NUMBER(10,2) NOT NULL, \
                 CONSTRAINT {base}_FK FOREIGN KEY (customer_id) REFERENCES {customers} (id) \
                 ON DELETE CASCADE)"
            ),
            format!("CREATE INDEX {base}_IX ON {orders} (total DESC, customer_id)"),
        ],
    )
    .await;
    let (customers_def, orders_def) = (load(&conn, &customers).await, load(&conn, &orders).await);

    // The copies: same shape, other names (constraint and index names are per schema).
    let rename = |t: &TableDef, name: &str, target: Option<(&str, &str)>| {
        let mut copy = t.clone();
        copy.table.name = name.into();
        for c in &mut copy.constraints {
            match c {
                ConstraintDef::PrimaryKey { name, .. }
                | ConstraintDef::Unique { name, .. }
                | ConstraintDef::Check { name, .. } => {
                    *name = name.as_ref().map(|n| format!("{n}2"))
                }
                ConstraintDef::ForeignKey {
                    name, target: t, ..
                } => {
                    *name = name.as_ref().map(|n| format!("{n}2"));
                    if let Some((_, to)) = target {
                        t.name = to.into();
                    }
                }
                ConstraintDef::Raw { .. } => {}
            }
        }
        for i in &mut copy.indexes {
            i.name = format!("{}2", i.name);
        }
        copy
    };
    let customers_copy = rename(&customers_def, &c2, None);
    let orders_copy = rename(&orders_def, &o2, Some((&customers, &c2)));
    for def in [&customers_copy, &orders_copy] {
        run(
            &conn,
            &g.ddl(&[SchemaChange::Create(ObjectDef::Table(def.clone()))])
                .unwrap(),
        )
        .await;
    }
    let read = (load(&conn, &c2).await, load(&conn, &o2).await);
    clean(&[
        format!("DROP TABLE {o2} PURGE"),
        format!("DROP TABLE {c2} PURGE"),
        format!("DROP TABLE {orders} PURGE"),
        format!("DROP TABLE {customers} PURGE"),
    ])
    .await;
    assert_eq!(read.0, customers_copy);
    assert_eq!(read.1, orders_copy);
    assert_eq!(
        customers_def.column("AGE").unwrap().default.as_deref(),
        Some("18")
    );
    assert!(orders_def.column("ID").unwrap().identity.is_some());
}

#[tokio::test]
async fn table_changes_apply() {
    sqlr_testkit::skip_container_tests!();
    let conn = support::connect().await;
    let g = OracleDialect;
    let base = unique_name("SQLR_ALT").to_uppercase();
    let (name, renamed, view) = (base.clone(), format!("{base}_R"), format!("{base}_V"));
    run(
        &conn,
        &[format!(
            "CREATE TABLE {name} (id NUMBER(10) PRIMARY KEY, label VARCHAR2(20), \
             age NUMBER(3) DEFAULT 18 NOT NULL, CONSTRAINT {base}_CK CHECK (age >= 0))"
        )],
    )
    .await;
    let t = table(&name);
    let before = load(&conn, &name).await;
    let label = before.column("LABEL").unwrap().clone();
    let age = before.column("AGE").unwrap().clone();

    let changes = vec![
        SchemaChange::AddColumn {
            table: t.clone(),
            column: ColumnDef {
                default: Some("'new'".into()),
                ..column("STATUS", "VARCHAR2(10)", true)
            },
        },
        // Wider type, NOT NULL, and a default, in one statement.
        SchemaChange::AlterColumn {
            table: t.clone(),
            before: label.clone(),
            after: ColumnDef {
                type_name: "VARCHAR2(40)".into(),
                nullable: false,
                default: Some("'x'".into()),
                ..label.clone()
            },
        },
        // The default goes away and the column becomes nullable and is renamed.
        SchemaChange::AlterColumn {
            table: t.clone(),
            before: age.clone(),
            after: ColumnDef {
                name: "YEARS".into(),
                nullable: true,
                default: None,
                ..age.clone()
            },
        },
        SchemaChange::AddIndex {
            table: t.clone(),
            index: IndexDef {
                name: format!("{base}_IX"),
                columns: vec![IndexColumn::column("STATUS")],
                unique: false,
                ..Default::default()
            },
            concurrently: false,
        },
        SchemaChange::DropConstraint {
            table: t.clone(),
            name: format!("{base}_CK"),
        },
    ];
    // Oracle keeps a check constraint on a renamed column working; it is dropped here to
    // keep the list short.
    run(&conn, &g.ddl(&changes).unwrap()).await;
    let after = load(&conn, &name).await;
    assert_eq!(after.column("LABEL").unwrap().type_name, "VARCHAR2(40)");
    assert!(!after.column("LABEL").unwrap().nullable);
    assert_eq!(
        after.column("LABEL").unwrap().default.as_deref(),
        Some("'x'")
    );
    assert_eq!(
        after.column("STATUS").unwrap().default.as_deref(),
        Some("'new'")
    );
    assert!(after.column("AGE").is_none());
    let years = after.column("YEARS").unwrap();
    assert!(years.nullable && years.default.is_none());
    assert!(after.indexes.iter().any(|i| i.name == format!("{base}_IX")));
    assert!(
        !after
            .constraints
            .iter()
            .any(|c| c.name() == Some(&format!("{base}_CK")))
    );

    // Rename an index, drop a column, rename the table.
    let changes = vec![
        SchemaChange::Rename {
            object: ObjectRef::child(ObjectKind::Index, &t, &format!("{base}_IX")),
            to: format!("{base}_IX2"),
        },
        SchemaChange::DropColumn {
            table: t.clone(),
            name: "STATUS".into(),
        },
        SchemaChange::Rename {
            object: ObjectRef::relation(ObjectKind::Table, &t),
            to: renamed.clone(),
        },
    ];
    run(&conn, &g.ddl(&changes).unwrap()).await;
    let moved = load(&conn, &renamed).await;
    assert!(moved.column("STATUS").is_none());

    // A view, replaced; then everything goes.
    let view_def = |query: &str| ViewDef {
        view: table(&view),
        query: query.into(),
        materialized: false,
        columns: vec![],
        comment: None,
        options: vec![],
        indexes: vec![],
    };
    run(
        &conn,
        &g.ddl(&[SchemaChange::Create(ObjectDef::View(view_def(&format!(
            "SELECT id FROM {renamed}"
        ))))])
        .unwrap(),
    )
    .await;
    run(
        &conn,
        &g.ddl(&[
            SchemaChange::ReplaceView(view_def(&format!("SELECT id, label FROM {renamed}"))),
            SchemaChange::Truncate {
                table: table(&renamed),
                cascade: false,
            },
            SchemaChange::Drop {
                object: ObjectRef::relation(ObjectKind::View, &table(&view)),
                cascade: false,
            },
            SchemaChange::Drop {
                object: ObjectRef::relation(ObjectKind::Table, &table(&renamed)),
                cascade: true,
            },
        ])
        .unwrap(),
    )
    .await;
}
