//! The schema model: definitions of database objects as object editors load and edit them
//! (spec §2, items 10–11). Columns, constraints and foreign keys are parts of a table.
//!
//! Text fields follow two conventions. Names (`name`, `columns`, `include`, collations) are
//! identifiers: DDL generators quote them through `Dialect::quote_ident`. Fields documented
//! as *expressions* (`default`, `generated`, check expressions, index predicates, view
//! queries, routine bodies, partition bounds) are SQL written as is.

use crate::admin::RoleDef;
use crate::table::TableRef;

/// The kind of a database object an object editor can load and edit.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum ObjectKind {
    /// A database (or catalog).
    Database,
    /// A schema (namespace).
    Schema,
    /// A table.
    Table,
    /// A view.
    View,
    /// A materialized view.
    MaterializedView,
    /// An index.
    Index,
    /// A sequence.
    Sequence,
    /// A stored function.
    Function,
    /// A stored procedure.
    Procedure,
    /// A trigger.
    Trigger,
    /// A role or user.
    Role,
}

impl ObjectKind {
    /// The SQL keyword(s) naming the kind (`MATERIALIZED VIEW`).
    pub fn keyword(self) -> &'static str {
        match self {
            ObjectKind::Database => "DATABASE",
            ObjectKind::Schema => "SCHEMA",
            ObjectKind::Table => "TABLE",
            ObjectKind::View => "VIEW",
            ObjectKind::MaterializedView => "MATERIALIZED VIEW",
            ObjectKind::Index => "INDEX",
            ObjectKind::Sequence => "SEQUENCE",
            ObjectKind::Function => "FUNCTION",
            ObjectKind::Procedure => "PROCEDURE",
            ObjectKind::Trigger => "TRIGGER",
            ObjectKind::Role => "ROLE",
        }
    }
}

/// Names one object. `parent` is the table of an index or trigger; `signature` the
/// identity arguments of a function or procedure (`a integer, b text`).
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct ObjectRef {
    /// What kind of object it is.
    pub kind: ObjectKind,
    /// Database that holds the object, when the driver qualifies by database.
    pub database: Option<String>,
    /// Schema that holds the object, when the driver has schemas.
    pub schema: Option<String>,
    /// The object's own name.
    pub name: String,
    /// Table name, for an index or trigger.
    pub parent: Option<String>,
    /// Identity arguments, for a function or procedure.
    pub signature: Option<String>,
}

impl ObjectRef {
    /// An object of `kind` named like `table` (tables, views, sequences).
    pub fn relation(kind: ObjectKind, table: &TableRef) -> Self {
        Self {
            kind,
            database: table.database.clone(),
            schema: table.schema.clone(),
            name: table.name.clone(),
            parent: None,
            signature: None,
        }
    }

    /// An index or trigger of `table`.
    pub fn child(kind: ObjectKind, table: &TableRef, name: &str) -> Self {
        Self {
            kind,
            database: table.database.clone(),
            schema: table.schema.clone(),
            name: name.to_string(),
            parent: Some(table.name.clone()),
            signature: None,
        }
    }

    /// The object's own name as a [`TableRef`] (database, schema, name).
    pub fn table_ref(&self) -> TableRef {
        TableRef {
            database: self.database.clone(),
            schema: self.schema.clone(),
            name: self.name.clone(),
        }
    }

    /// The table of an index or trigger.
    pub fn parent_table(&self) -> Option<TableRef> {
        self.parent.as_ref().map(|parent| TableRef {
            database: self.database.clone(),
            schema: self.schema.clone(),
            name: parent.clone(),
        })
    }
}

/// How the server fills a column's value.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Identity {
    /// `GENERATED ALWAYS AS IDENTITY`: written values are refused.
    Always,
    /// `GENERATED BY DEFAULT AS IDENTITY`.
    ByDefault,
    /// MySQL `AUTO_INCREMENT`, SQLite `AUTOINCREMENT`.
    AutoIncrement,
}

/// A table column as an object editor loads and edits it.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ColumnDef {
    /// Column name.
    pub name: String,
    /// Declared type as the server prints it.
    pub type_name: String,
    /// Whether the column accepts `NULL`.
    pub nullable: bool,
    /// Default expression.
    pub default: Option<String>,
    /// Generation expression of a computed column.
    pub generated: Option<String>,
    /// With `generated`: stored (`true`) or virtual.
    pub generated_stored: bool,
    /// How the server fills the value, for an identity or auto-increment column.
    pub identity: Option<Identity>,
    /// Column comment.
    pub comment: Option<String>,
    /// Collation name, when it is not the type's or table's default.
    pub collation: Option<String>,
    /// MySQL `ON UPDATE` expression (`CURRENT_TIMESTAMP`).
    pub on_update: Option<String>,
}

/// One key part of an index. Column names and SQL expressions remain distinct even
/// when a real column name happens to be wrapped in parentheses.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct IndexColumn {
    /// The column name, or the SQL expression when `expression` is set.
    pub expr: String,
    /// Whether `expr` is SQL rather than a column name that must be quoted.
    pub expression: bool,
    /// Descending order.
    pub desc: bool,
    /// Prefix length of a MySQL key part (`name(10)`).
    pub prefix: Option<u32>,
}

impl IndexColumn {
    /// A key part on the plain column `name`.
    pub fn column(name: &str) -> Self {
        Self {
            expr: name.to_string(),
            ..Default::default()
        }
    }

    /// True when `expr` is an expression rather than a column name.
    pub fn is_expression(&self) -> bool {
        self.expression
    }
}

/// An index as an object editor loads and edits it.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct IndexDef {
    /// Index name.
    pub name: String,
    /// Key parts, in order.
    pub columns: Vec<IndexColumn>,
    /// Whether the index enforces uniqueness.
    pub unique: bool,
    /// Access method (`btree`, `gin`, MySQL `FULLTEXT`…).
    pub method: Option<String>,
    /// Partial index condition (expression).
    pub predicate: Option<String>,
    /// Non-key columns (`INCLUDE`).
    pub include: Vec<String>,
    /// The whole `CREATE INDEX` statement as the server prints it, for an index the other
    /// fields cannot express (operator classes, `NULLS` order, per-column collations,
    /// storage parameters, tablespace). It is written back unchanged; the other fields
    /// describe the index for display.
    pub definition: Option<String>,
}

/// The referential action of a foreign key on update or delete.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum FkAction {
    /// `NO ACTION`: the check fails when the referenced row changes.
    #[default]
    NoAction,
    /// `RESTRICT`: refuses the change right away.
    Restrict,
    /// `CASCADE`: applies the change to the referencing rows.
    Cascade,
    /// `SET NULL`: nulls the referencing columns.
    SetNull,
    /// `SET DEFAULT`: sets the referencing columns to their defaults.
    SetDefault,
}

impl FkAction {
    /// The SQL keywords of the action (`SET NULL`).
    pub fn sql(self) -> &'static str {
        match self {
            FkAction::NoAction => "NO ACTION",
            FkAction::Restrict => "RESTRICT",
            FkAction::Cascade => "CASCADE",
            FkAction::SetNull => "SET NULL",
            FkAction::SetDefault => "SET DEFAULT",
        }
    }

    /// Parses `NO ACTION`, `RESTRICT`, `CASCADE`, `SET NULL`, `SET DEFAULT` (any case).
    pub fn parse(text: &str) -> Option<Self> {
        let words: Vec<String> = text
            .split_whitespace()
            .map(|w| w.to_ascii_uppercase())
            .collect();
        match words.join(" ").as_str() {
            "NO ACTION" => Some(FkAction::NoAction),
            "RESTRICT" => Some(FkAction::Restrict),
            "CASCADE" => Some(FkAction::Cascade),
            "SET NULL" => Some(FkAction::SetNull),
            "SET DEFAULT" => Some(FkAction::SetDefault),
            _ => None,
        }
    }
}

/// A table constraint.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ConstraintDef {
    /// The primary key.
    PrimaryKey {
        /// Constraint name, when it has one.
        name: Option<String>,
        /// Key columns.
        columns: Vec<String>,
    },
    /// A unique constraint.
    Unique {
        /// Constraint name, when it has one.
        name: Option<String>,
        /// Constrained columns.
        columns: Vec<String>,
    },
    /// A check constraint.
    Check {
        /// Constraint name, when it has one.
        name: Option<String>,
        /// The condition (expression).
        expression: String,
    },
    /// A foreign key.
    ForeignKey {
        /// Constraint name, when it has one.
        name: Option<String>,
        /// Referencing columns of this table.
        columns: Vec<String>,
        /// The referenced table.
        target: TableRef,
        /// Empty when the target's primary key is meant (SQLite).
        target_columns: Vec<String>,
        /// Action when a referenced row is updated.
        on_update: FkAction,
        /// Action when a referenced row is deleted.
        on_delete: FkAction,
        /// `DEFERRABLE`: the check may be deferred to the end of the transaction.
        deferrable: bool,
        /// `INITIALLY DEFERRED` (with `deferrable`): deferred unless the transaction says
        /// otherwise.
        initially_deferred: bool,
    },
    /// A constraint the model cannot express, as the server prints it after its name
    /// (`EXCLUDE USING gist (…)`, `CHECK (…) NOT VALID`, `FOREIGN KEY … MATCH FULL`). It
    /// is written back unchanged.
    Raw {
        /// Constraint name, when it has one.
        name: Option<String>,
        /// The definition, as the server prints it after the name.
        definition: String,
    },
}

impl ConstraintDef {
    /// The constraint's name, when it has one.
    pub fn name(&self) -> Option<&str> {
        match self {
            ConstraintDef::PrimaryKey { name, .. }
            | ConstraintDef::Unique { name, .. }
            | ConstraintDef::Check { name, .. }
            | ConstraintDef::ForeignKey { name, .. }
            | ConstraintDef::Raw { name, .. } => name.as_deref(),
        }
    }

    /// Whether the constraint is a foreign key (also a raw one that reads `FOREIGN KEY`).
    pub fn is_foreign_key(&self) -> bool {
        match self {
            ConstraintDef::ForeignKey { .. } => true,
            ConstraintDef::Raw { definition, .. } => definition
                .trim_start()
                .to_ascii_uppercase()
                .starts_with("FOREIGN KEY"),
            _ => false,
        }
    }

    /// The columns the constraint names on its own table (none for a check or a raw
    /// constraint).
    pub fn columns(&self) -> &[String] {
        match self {
            ConstraintDef::PrimaryKey { columns, .. }
            | ConstraintDef::Unique { columns, .. }
            | ConstraintDef::ForeignKey { columns, .. } => columns,
            ConstraintDef::Check { .. } | ConstraintDef::Raw { .. } => &[],
        }
    }
}

/// A partition of a partitioned table. `bound` is the expression after the partition name
/// (`FOR VALUES FROM (1) TO (10)`, `DEFAULT`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PartitionDef {
    /// The partition's own table.
    pub table: TableRef,
    /// The partition bound expression.
    pub bound: String,
}

/// A table as an object editor loads and edits it: columns, constraints, indexes, triggers and partitions.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TableDef {
    /// The table's name.
    pub table: TableRef,
    /// Columns, in order.
    pub columns: Vec<ColumnDef>,
    /// Primary key, unique, check, foreign key and raw constraints.
    pub constraints: Vec<ConstraintDef>,
    /// Indexes on the table.
    pub indexes: Vec<IndexDef>,
    /// Triggers on the table.
    pub triggers: Vec<TriggerDef>,
    /// Table comment.
    pub comment: Option<String>,
    /// Driver-specific options (engine, charset, tablespace, `WITHOUT ROWID`, `STRICT`,
    /// the partition key…), as the driver's introspection names them.
    pub options: Vec<(String, String)>,
    /// Partitions, when the table is partitioned.
    pub partitions: Vec<PartitionDef>,
    /// Objects outside the table that name it, which a table rebuild drops and creates
    /// again (SQLite views and other tables' triggers). Not part of the table's own
    /// definition: [`crate::diff_table`] ignores them.
    pub dependents: Vec<DependentDef>,
}

/// An object that names a table, as its `CREATE` statement.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DependentDef {
    /// [`ObjectKind::View`] or [`ObjectKind::Trigger`].
    pub kind: ObjectKind,
    /// The dependent object's name.
    pub name: String,
    /// Its `CREATE` statement.
    pub sql: String,
}

impl TableDef {
    /// An empty table named `table`.
    pub fn new(table: TableRef) -> Self {
        Self {
            table,
            columns: Vec::new(),
            constraints: Vec::new(),
            indexes: Vec::new(),
            triggers: Vec::new(),
            comment: None,
            options: Vec::new(),
            partitions: Vec::new(),
            dependents: Vec::new(),
        }
    }

    /// The column called `name`.
    pub fn column(&self, name: &str) -> Option<&ColumnDef> {
        self.columns.iter().find(|c| c.name == name)
    }

    /// The value of the driver-specific option `key`.
    pub fn option(&self, key: &str) -> Option<&str> {
        self.options
            .iter()
            .find(|(k, _)| k == key)
            .map(|(_, v)| v.as_str())
    }

    /// The primary key columns, when the table has one.
    pub fn primary_key(&self) -> Option<&[String]> {
        self.constraints.iter().find_map(|c| match c {
            ConstraintDef::PrimaryKey { columns, .. } => Some(columns.as_slice()),
            _ => None,
        })
    }

    /// The columns that identify one row: the primary key, else the first unique
    /// constraint or unique plain-column index whose columns are all `NOT NULL`.
    pub fn row_key(&self) -> Option<Vec<String>> {
        if let Some(pk) = self.primary_key().filter(|pk| !pk.is_empty()) {
            return Some(pk.to_vec());
        }
        let not_null = |cols: &[String]| {
            !cols.is_empty()
                && cols
                    .iter()
                    .all(|n| self.column(n).is_some_and(|c| !c.nullable))
        };
        let uniques = self.constraints.iter().filter_map(|c| match c {
            ConstraintDef::Unique { columns, .. } => Some(columns.clone()),
            _ => None,
        });
        let indexes = self
            .indexes
            .iter()
            .filter(|i| i.unique && i.predicate.is_none())
            .filter(|i| i.columns.iter().all(|c| !c.is_expression()))
            .map(|i| i.columns.iter().map(|c| c.expr.clone()).collect());
        uniques
            .chain(indexes)
            .find(|cols: &Vec<String>| not_null(cols))
    }
}

/// A view or materialized view as an object editor loads and edits it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ViewDef {
    /// The view's name.
    pub view: TableRef,
    /// The `SELECT` (expression).
    pub query: String,
    /// Whether the view is materialized.
    pub materialized: bool,
    /// Explicit column names; empty when the query names them.
    pub columns: Vec<String>,
    /// View comment.
    pub comment: Option<String>,
    /// Driver-specific options.
    pub options: Vec<(String, String)>,
    /// Indexes of a materialized view.
    pub indexes: Vec<IndexDef>,
}

/// A sequence as an object editor loads and edits it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SequenceDef {
    /// The sequence's name.
    pub sequence: TableRef,
    /// Data type of the values.
    pub data_type: Option<String>,
    /// First value.
    pub start: Option<i64>,
    /// Step between values.
    pub increment: Option<i64>,
    /// Lowest value.
    pub min_value: Option<i64>,
    /// Highest value.
    pub max_value: Option<i64>,
    /// Number of values preallocated.
    pub cache: Option<i64>,
    /// Whether the sequence wraps around at its limits.
    pub cycle: bool,
    /// Sequence comment.
    pub comment: Option<String>,
}

/// A function or procedure. `arguments` and `returns` are written as is (`a integer,
/// b text DEFAULT 'x'`, `SETOF record`); `body` is the routine's source.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RoutineDef {
    /// Schema of the routine.
    pub schema: Option<String>,
    /// Routine name.
    pub name: String,
    /// [`ObjectKind::Function`] or [`ObjectKind::Procedure`].
    pub kind: ObjectKind,
    /// The parameter list, as written in the declaration.
    pub arguments: String,
    /// The argument types that identify the routine among overloads (PostgreSQL
    /// `a integer, b text`: no defaults); the signature of its [`ObjectRef`].
    pub identity_arguments: Option<String>,
    /// The return type, for a function.
    pub returns: Option<String>,
    /// Language of the body (`plpgsql`, `sql`).
    pub language: Option<String>,
    /// The routine's source.
    pub body: String,
    /// Driver-specific attributes (volatility, security, determinism, comment…).
    pub options: Vec<(String, String)>,
}

/// A trigger. `timing` is `BEFORE`, `AFTER` or `INSTEAD OF`; `events` are `INSERT`,
/// `UPDATE`, `DELETE`, `TRUNCATE` or `UPDATE OF …` (written as is). `condition` (the `WHEN`
/// expression) and `body` (the action: a function call or statements) are written as is.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TriggerDef {
    /// Trigger name.
    pub name: String,
    /// The table the trigger fires on.
    pub table: TableRef,
    /// When it fires: `BEFORE`, `AFTER` or `INSTEAD OF`.
    pub timing: String,
    /// The events that fire it.
    pub events: Vec<String>,
    /// Whether it fires per row rather than per statement.
    pub for_each_row: bool,
    /// The `WHEN` expression, when it has one.
    pub condition: Option<String>,
    /// The action: a function call or statements.
    pub body: String,
}

/// A schema as an object editor loads and edits it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SchemaDef {
    /// Schema name.
    pub name: String,
    /// Schema owner.
    pub owner: Option<String>,
    /// Schema comment.
    pub comment: Option<String>,
}

/// A database as an object editor loads and edits it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DatabaseDef {
    /// Database name.
    pub name: String,
    /// Driver-specific options (charset, collation, encoding...).
    pub options: Vec<(String, String)>,
}

/// The definition of one object, by kind.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ObjectDef {
    /// A database.
    Database(DatabaseDef),
    /// A schema.
    Schema(SchemaDef),
    /// A table.
    Table(TableDef),
    /// A view or materialized view.
    View(ViewDef),
    /// A sequence.
    Sequence(SequenceDef),
    /// A function or procedure.
    Routine(RoutineDef),
    /// A trigger.
    Trigger(TriggerDef),
    /// An index on `table`.
    Index {
        /// The table the index belongs to.
        table: TableRef,
        /// The index definition.
        index: IndexDef,
    },
    /// A role or user.
    Role(RoleDef),
}

impl ObjectDef {
    /// The kind of the object, telling a materialized view from a view.
    pub fn kind(&self) -> ObjectKind {
        match self {
            ObjectDef::Database(_) => ObjectKind::Database,
            ObjectDef::Schema(_) => ObjectKind::Schema,
            ObjectDef::Table(_) => ObjectKind::Table,
            ObjectDef::View(v) if v.materialized => ObjectKind::MaterializedView,
            ObjectDef::View(_) => ObjectKind::View,
            ObjectDef::Sequence(_) => ObjectKind::Sequence,
            ObjectDef::Routine(r) => r.kind,
            ObjectDef::Trigger(_) => ObjectKind::Trigger,
            ObjectDef::Index { .. } => ObjectKind::Index,
            ObjectDef::Role(_) => ObjectKind::Role,
        }
    }

    /// The reference that names this object.
    pub fn object_ref(&self) -> ObjectRef {
        let named = |kind, schema: Option<&String>, name: &str| ObjectRef {
            kind,
            database: None,
            schema: schema.cloned(),
            name: name.to_string(),
            parent: None,
            signature: None,
        };
        match self {
            ObjectDef::Database(d) => named(ObjectKind::Database, None, &d.name),
            ObjectDef::Schema(s) => named(ObjectKind::Schema, None, &s.name),
            ObjectDef::Table(t) => ObjectRef::relation(ObjectKind::Table, &t.table),
            ObjectDef::View(v) => ObjectRef::relation(self.kind(), &v.view),
            ObjectDef::Sequence(s) => ObjectRef::relation(ObjectKind::Sequence, &s.sequence),
            ObjectDef::Routine(r) => ObjectRef {
                signature: r.identity_arguments.clone(),
                ..named(r.kind, r.schema.as_ref(), &r.name)
            },
            ObjectDef::Trigger(t) => ObjectRef::child(ObjectKind::Trigger, &t.table, &t.name),
            ObjectDef::Index { table, index } => {
                ObjectRef::child(ObjectKind::Index, table, &index.name)
            }
            ObjectDef::Role(r) => named(ObjectKind::Role, None, &r.name),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn t(name: &str) -> TableRef {
        TableRef {
            database: None,
            schema: Some("public".into()),
            name: name.into(),
        }
    }

    fn col(name: &str, nullable: bool) -> ColumnDef {
        ColumnDef {
            name: name.into(),
            type_name: "integer".into(),
            nullable,
            ..Default::default()
        }
    }

    #[test]
    fn row_key_prefers_pk_then_not_null_unique() {
        let mut table = TableDef::new(t("t"));
        table.columns = vec![col("a", true), col("b", false)];
        table.indexes.push(IndexDef {
            name: "i".into(),
            columns: vec![IndexColumn::column("a")],
            unique: true,
            ..Default::default()
        });
        assert_eq!(table.row_key(), None);
        table.constraints.push(ConstraintDef::Unique {
            name: None,
            columns: vec!["b".into()],
        });
        assert_eq!(table.row_key(), Some(vec!["b".to_string()]));
        table.constraints.push(ConstraintDef::PrimaryKey {
            name: None,
            columns: vec!["a".into()],
        });
        assert_eq!(table.row_key(), Some(vec!["a".to_string()]));
    }

    #[test]
    fn object_refs_of_definitions() {
        let index = ObjectDef::Index {
            table: t("t"),
            index: IndexDef {
                name: "i".into(),
                ..Default::default()
            },
        };
        let r = index.object_ref();
        assert_eq!(
            (r.kind, r.parent.as_deref()),
            (ObjectKind::Index, Some("t"))
        );
        assert_eq!(r.parent_table(), Some(t("t")));
        assert_eq!(FkAction::parse("set  null"), Some(FkAction::SetNull));
        assert_eq!(FkAction::Cascade.sql(), "CASCADE");
        assert!(
            IndexColumn {
                expr: "(lower(x))".into(),
                expression: true,
                ..Default::default()
            }
            .is_expression()
        );
        assert!(!IndexColumn::column("x").is_expression());
        assert!(!IndexColumn::column("(1)").is_expression());
    }
}
